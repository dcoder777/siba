$user = admin_user();
$isOwner = ($user['role'] ?? '') === 'owner';
$canManageHR = can_user_delete($pdo, (int)$user['id'], 'hr') || $isOwner;
$error = '';
$success = '';

// ─── Export CSV ───
if (isset($_GET['export']) && $_GET['export'] === 'csv') {
    $runId = isset($_GET['view_run']) ? (int) $_GET['view_run'] : null;
    header('Content-Type: text/csv');
    header('Content-Disposition: attachment; filename="payroll_export_' . date('Ymd_His') . '.csv"');
    $output = fopen('php://output', 'w');
    
    if ($runId) {
        fputcsv($output, ['Employee Name', 'Code', 'Department', 'Payout Account', 'CTC Amount', 'Gross Amount', 'Deductions', 'Net Payout']);
        $stmt = $pdo->prepare("SELECT e.name, e.employee_code, e.department, e.payout_account, pi.ctc_amount, pi.gross_amount, pi.deductions_amount, pi.net_payout
                               FROM payroll_items pi 
                               JOIN employees e ON e.id = pi.employee_id 
                               WHERE pi.payroll_run_id = ? 
                               ORDER BY e.name");
        $stmt->execute([$runId]);
        while ($row = $stmt->fetch(PDO::FETCH_ASSOC)) {
            fputcsv($output, $row);
        }
    } else {
        fputcsv($output, ['Month Label', 'Generated At', 'Generated By', 'Staff Count', 'Total Payout']);
        $stmt = $pdo->query("SELECT pr.payroll_month, pr.generated_at, u.name AS generated_by_name,
                    (SELECT COUNT(*) FROM payroll_items pi WHERE pi.payroll_run_id = pr.id) as staff_count,
                    (SELECT SUM(net_payout) FROM payroll_items pi WHERE pi.payroll_run_id = pr.id) as total_payout
                    FROM payroll_runs pr 
                    LEFT JOIN users u ON u.id = pr.generated_by
                    ORDER BY pr.id DESC");
        while ($row = $stmt->fetch(PDO::FETCH_ASSOC)) {
            $row['generated_by_name'] = $row['generated_by_name'] ?: 'System';
            fputcsv($output, $row);
        }
    }
    fclose($output);
    exit;
}

// ─── POST handlers ───
if ($_SERVER['REQUEST_METHOD'] === 'POST' && verify_csrf()) {
    $action = trim((string) ($_POST['action'] ?? ''));

    // Generate Payroll
    if ($action === 'generate_payroll') {
        $monthLabel = trim((string) ($_POST['month_label'] ?? ''));
        if (!preg_match('/^\d{4}-\d{2}$/', $monthLabel)) {
            $error = 'Invalid month format. Please use YYYY-MM (e.g., 2026-04).';
        } else {
            // Check if already generated
            $checkStmt = $pdo->prepare("SELECT COUNT(*) FROM payroll_runs WHERE payroll_month = ?");
            $checkStmt->execute([$monthLabel]);
            if ((int) $checkStmt->fetchColumn() > 0) {
                $error = "Payroll for $monthLabel has already been generated.";
            } else {
                // We could call the API, but since we have PDO, we do it directly just like the controller.
                $employees = $pdo->query('SELECT * FROM employees WHERE status = "active"')->fetchAll();
                
                if (empty($employees)) {
                    $error = 'No active employees found to generate payroll.';
                } else {
                    $pdo->beginTransaction();
                    try {
                        $pdo->prepare(
                            'INSERT INTO payroll_runs (payroll_month, generated_at, generated_by) VALUES (?, NOW(), ?)'
                        )->execute([$monthLabel, $user['id']]);

                        $runId = (int) $pdo->lastInsertId();
                        $itemStmt = $pdo->prepare(
                            'INSERT INTO payroll_items (
                                payroll_run_id, employee_id, ctc_amount, gross_amount, deductions_amount, net_payout
                             ) VALUES (?, ?, ?, ?, ?, ?)'
                        );

                        foreach ($employees as $employee) {
                            $monthlyGross = (float)$employee['basic_salary'] + (float)$employee['hra'] + (float)$employee['transport_allowance'] + (float)$employee['special_allowance'];
                            $deductions = (float)$employee['pf_deduction'] + (float)$employee['pt_deduction'];
                            $net = $monthlyGross - $deductions;

                            $itemStmt->execute([
                                $runId,
                                $employee['id'],
                                $employee['ctc'],
                                $monthlyGross,
                                $deductions,
                                $net,
                            ]);
                        }

                        $pdo->commit();
                        $success = 'Payroll for ' . $monthLabel . ' generated successfully for ' . count($employees) . ' employees.';
                    } catch (\Throwable $e) {
                        $pdo->rollBack();
                        $error = 'Payroll generation failed: ' . $e->getMessage();
                    }
                }
            }
        }
    }

    // Delete Payroll Run
    if ($action === 'delete_payroll' && isset($_POST['id'])) {
        if (!$canManageHR) {
            $error = 'You do not have permission to delete payroll runs.';
        } else {
            $id = (int) $_POST['id'];
            $pdo->prepare("DELETE FROM payroll_runs WHERE id=?")->execute([$id]);
            $success = 'Payroll run deleted.';
        }
    }

    header('Location: payroll-execution.php' . ($error !== '' ? '?error=' . urlencode($error) : ''));
    exit;
}

// ─── View details of a run ───
$viewRunId = isset($_GET['view_run']) ? (int) $_GET['view_run'] : null;
