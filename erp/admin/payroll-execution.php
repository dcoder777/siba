    if ($viewRunData) {
        $itemStmt = $pdo->prepare("SELECT pi.*, e.name AS employee_name, e.employee_code, e.department, e.payout_account 
                                   FROM payroll_items pi 
                                   JOIN employees e ON e.id = pi.employee_id 
                                   WHERE pi.payroll_run_id = ? 
                                   ORDER BY e.name");
        $itemStmt->execute([$viewRunId]);
        $payrollItems = $itemStmt->fetchAll(PDO::FETCH_ASSOC);
    }
}

